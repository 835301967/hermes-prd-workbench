export type Block =
  | { type: "heading"; level: 1 | 2 | 3; text: string }
  | { type: "paragraph"; text: string }
  | { type: "list"; ordered: boolean; items: string[] }
  | { type: "quote"; text: string }
  | { type: "code"; text: string }
  | { type: "diagram"; lang: string; code: string }
  | { type: "table"; rows: string[][] };

export function isDiagramBlock(lang: string, code: string): boolean {
  const cleanLang = (lang || "").trim().toLowerCase();
  if (cleanLang === "mermaid") return true;
  if (["flowchart", "sequencediagram", "statediagram", "erdiagram", "classdiagram", "gantt"].includes(cleanLang)) {
    return true;
  }
  const trimmed = (code || "").trim();
  return /^(graph\s+[A-Za-z]{2}|flowchart\s+[A-Za-z]{2}|sequenceDiagram|stateDiagram(-v2)?|classDiagram|erDiagram|gantt|pie\b|journey\b|gitGraph\b)/i.test(
    trimmed
  );
}

export function parseMarkdownBlocks(markdown: string): Block[] {
  const lines = unwrapMarkdown(markdown).split(/\r?\n/);
  const blocks: Block[] = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) {
      i += 1;
      continue;
    }
    const heading = line.match(/^(#{1,3})\s+(.+)$/);
    if (heading) {
      blocks.push({ type: "heading", level: heading[1].length as 1 | 2 | 3, text: heading[2].trim() });
      i += 1;
      continue;
    }
    if (line.startsWith("> ")) {
      const quote: string[] = [];
      while (i < lines.length && lines[i].startsWith("> ")) {
        quote.push(lines[i].replace(/^>\s?/, ""));
        i += 1;
      }
      blocks.push({ type: "quote", text: quote.join("\n") });
      continue;
    }
    if (line.startsWith("```")) {
      const match = line.match(/^```([a-zA-Z0-9_-]*)/);
      const lang = match ? match[1].trim() : "";
      i += 1;
      const code: string[] = [];
      while (i < lines.length && !lines[i].startsWith("```")) {
        code.push(lines[i]);
        i += 1;
      }
      if (i < lines.length) i += 1;
      const codeText = code.join("\n");
      if (isDiagramBlock(lang, codeText)) {
        blocks.push({ type: "diagram", lang: lang || "mermaid", code: codeText });
      } else {
        blocks.push({ type: "code", text: codeText });
      }
      continue;
    }
    if (line.trim().startsWith("|") && i + 1 < lines.length && /^\s*\|?\s*-+/.test(lines[i + 1])) {
      const rows: string[][] = [splitTableRow(line)];
      i += 2;
      while (i < lines.length && lines[i].trim().startsWith("|")) {
        rows.push(splitTableRow(lines[i]));
        i += 1;
      }
      blocks.push({ type: "table", rows });
      continue;
    }
    if (/^\s*([-*]|\d+\.)\s+/.test(line)) {
      const ordered = /^\s*\d+\.\s+/.test(line);
      const items: string[] = [];
      while (i < lines.length && /^\s*([-*]|\d+\.)\s+/.test(lines[i])) {
        items.push(lines[i].replace(/^\s*([-*]|\d+\.)\s+/, ""));
        i += 1;
      }
      blocks.push({ type: "list", ordered, items });
      continue;
    }
    const para: string[] = [line];
    i += 1;
    while (i < lines.length && lines[i].trim() && !/^(#{1,3}\s+|```|\s*([-*]|\d+\.)\s+|>\s|\|)/.test(lines[i])) {
      para.push(lines[i]);
      i += 1;
    }
    blocks.push({ type: "paragraph", text: para.join("\n") });
  }
  return blocks;
}

function splitTableRow(line: string) {
  return line
    .trim()
    .replace(/^\|/, "")
    .replace(/\|$/, "")
    .split("|")
    .map((cell) => cell.trim());
}

export interface RenderedDiagram {
  dataUrl: string;
  targetWidth: number;
  targetHeight: number;
}

let mermaidInitPromise: Promise<typeof import("mermaid")["default"]> | null = null;

async function getMermaidInstance() {
  if (typeof window === "undefined" || typeof document === "undefined") {
    return null;
  }
  if (!mermaidInitPromise) {
    mermaidInitPromise = (async () => {
      const { default: mermaid } = await import("mermaid");
      mermaid.initialize({
        startOnLoad: false,
        theme: "default",
        securityLevel: "strict",
        maxTextSize: 20000,
        maxEdges: 500,
        flowchart: { htmlLabels: false },
        fontFamily: "Inter, -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif",
        themeVariables: {
          primaryColor: "#EBF5FF",
          primaryTextColor: "#1E3A8A",
          primaryBorderColor: "#3B82F6",
          lineColor: "#64748B",
          secondaryColor: "#F1F5F9",
          tertiaryColor: "#FFFFFF",
        },
      });
      return mermaid;
    })();
  }
  return mermaidInitPromise;
}

export function prepareDiagramCodeForExport(code: string): string {
  const trimmed = (code || "").trim();
  if (!trimmed) return "";
  if (/^%%\{init:/i.test(trimmed)) {
    if (!/htmlLabels/i.test(trimmed)) {
      return trimmed.replace(
        /^%%\{init:\s*\{/i,
        "%%{init: {'htmlLabels': false, 'flowchart': {'htmlLabels': false}, "
      );
    }
    return trimmed;
  }
  return `%%{init: {'htmlLabels': false, 'flowchart': {'htmlLabels': false}}}%%\n${trimmed}`;
}

export async function renderDiagramToPng(code: string): Promise<RenderedDiagram | null> {
  if (
    typeof window === "undefined" ||
    typeof document === "undefined" ||
    typeof Image === "undefined" ||
    typeof document.createElement("canvas").getContext !== "function"
  ) {
    return null;
  }
  const rawCode = (code || "").trim();
  if (!rawCode) {
    return null;
  }


  const diagramId = `docx_mermaid_${Date.now()}_${Math.random().toString(36).slice(2, 8)}`;
  try {
    const mermaid = await getMermaidInstance();
    if (!mermaid) {
      return null;
    }

    const { svg: rawSvg } = await mermaid.render(diagramId, safeDiagramCode(rawCode));
    const svg = sanitizeDiagramSvg(rawSvg);
    const tempEl = document.getElementById(diagramId);
    if (tempEl && !tempEl.closest(".mermaid-viewport")) {
      tempEl.remove();
    }

    let width = 0;
    let height = 0;
    const vbMatch = svg.match(/viewBox=["']\s*([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\s*["']/i);
    if (vbMatch) {
      const vbWidth = parseFloat(vbMatch[3]);
      const vbHeight = parseFloat(vbMatch[4]);
      if (!isNaN(vbWidth) && vbWidth > 0 && !isNaN(vbHeight) && vbHeight > 0) {
        width = vbWidth;
        height = vbHeight;
      }
    }

    if (!width || !height) {
      const wMatch = svg.match(/width=["']([-\d.]+)px?["']/i);
      const hMatch = svg.match(/height=["']([-\d.]+)px?["']/i);
      if (wMatch && hMatch) {
        width = parseFloat(wMatch[1]);
        height = parseFloat(hMatch[1]);
      }
    }

    if (!width || !height || isNaN(width) || isNaN(height)) {
      width = 650;
      height = 400;
    }

    let normalizedSvg = svg;
    try {
      const parser = new DOMParser();
      const doc = parser.parseFromString(svg, "image/svg+xml");
      const svgEl = doc.documentElement;
      svgEl.setAttribute("width", Math.round(width).toString());
      svgEl.setAttribute("height", Math.round(height).toString());
      normalizedSvg = new XMLSerializer().serializeToString(svgEl);
    } catch {
      // ignore
    }

    const svgBlob = new Blob([normalizedSvg], { type: "image/svg+xml;charset=utf-8" });
    const url = URL.createObjectURL(svgBlob);

    const img = new Image();
    const loaded = await new Promise<boolean>((resolve) => {
      const timer = window.setTimeout(() => {
        resolve(false);
      }, 3500);
      img.onload = () => {
        window.clearTimeout(timer);
        resolve(true);
      };
      img.onerror = () => {
        window.clearTimeout(timer);
        resolve(false);
      };
      img.src = url;
    });

    URL.revokeObjectURL(url);
    if (!loaded) {
      return null;
    }

    const scale = 2;
    const canvas = document.createElement("canvas");
    canvas.width = Math.max(1, Math.round(width * scale));
    canvas.height = Math.max(1, Math.round(height * scale));
    const ctx = canvas.getContext("2d");
    if (!ctx) {
      return null;
    }

    ctx.fillStyle = "#FFFFFF";
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    ctx.drawImage(img, 0, 0, canvas.width, canvas.height);

    const dataUrl = canvas.toDataURL("image/png");

    const MAX_DOCX_WIDTH = 560;
    let targetWidth = width;
    let targetHeight = height;

    if (targetWidth > MAX_DOCX_WIDTH) {
      const ratio = MAX_DOCX_WIDTH / targetWidth;
      targetWidth = MAX_DOCX_WIDTH;
      targetHeight = Math.round(targetHeight * ratio);
    }

    const MAX_DOCX_HEIGHT = 700;
    if (targetHeight > MAX_DOCX_HEIGHT) {
      const ratio = MAX_DOCX_HEIGHT / targetHeight;
      targetHeight = MAX_DOCX_HEIGHT;
      targetWidth = Math.round(targetWidth * ratio);
    }

    return {
      dataUrl,
      targetWidth: Math.max(10, Math.round(targetWidth)),
      targetHeight: Math.max(10, Math.round(targetHeight)),
    };
  } catch {
    const errEl = document.getElementById("d" + diagramId) || document.getElementById(diagramId);
    if (errEl) {
      errEl.remove();
    }
    return null;
  }
}

export async function markdownToDocxBlob(title: string, markdown: string) {
  const {
    AlignmentType,
    File: DocxDocument,
    HeadingLevel,
    ImageRun,
    Packer,
    Paragraph,
    Table,
    TableCell,
    TableRow,
    TextRun,
    WidthType,
  } = await import("docx");
  const blocks = parseMarkdownBlocks(markdown);
  const children: (DocxParagraph | DocxTable)[] = [new Paragraph({ text: title || "PRD", heading: HeadingLevel.TITLE })];
  for (const block of blocks) {
    if (block.type === "heading") {
      const heading = block.level === 1 ? HeadingLevel.HEADING_1 : block.level === 2 ? HeadingLevel.HEADING_2 : HeadingLevel.HEADING_3;
      children.push(new Paragraph({ text: block.text, heading }));
    } else if (block.type === "paragraph") {
      children.push(new Paragraph(block.text));
    } else if (block.type === "quote" || block.type === "code") {
      children.push(new Paragraph({ children: [new TextRun({ text: block.text, italics: block.type === "quote" })] }));
    } else if (block.type === "diagram") {
      const rendered = await renderDiagramToPng(block.code);
      if (rendered) {
        children.push(
          new Paragraph({
            alignment: AlignmentType.CENTER,
            spacing: { before: 240, after: 120 },
            children: [
              new ImageRun({
                data: rendered.dataUrl,
                transformation: {
                  width: rendered.targetWidth,
                  height: rendered.targetHeight,
                },
                altText: {
                  title: "业务架构与流程推演图",
                  description: "PRD 架构与流程图",
                  name: "diagram.png",
                },
              }),
            ],
          })
        );
        children.push(
          new Paragraph({
            alignment: AlignmentType.CENTER,
            spacing: { before: 0, after: 240 },
            children: [
              new TextRun({
                text: "【图】业务流转与架构推演图",
                italics: true,
                size: 18,
                color: "666666",
              }),
            ],
          })
        );
      } else {
        children.push(
          new Paragraph({
            children: [
              new TextRun({
                text: `【业务流转 / 架构图源码 (${block.lang})】\n${block.code}`,
                italics: false,
              }),
            ],
          })
        );
      }
    } else if (block.type === "list") {
      block.items.forEach((item, index) => {
        const prefix = block.ordered ? `${index + 1}. ` : "• ";
        children.push(new Paragraph(prefix + item));
      });
    } else if (block.type === "table") {
      children.push(
        new Table({
          width: { size: 100, type: WidthType.PERCENTAGE },
          rows: block.rows.map(
            (row) =>
              new TableRow({
                children: row.map((cell) => new TableCell({ children: [new Paragraph(cell)] })),
              })
          ),
        })
      );
    }
  }
  const doc = new DocxDocument({
    sections: [{ children }],
  });
  return Packer.toBlob(doc);
}

export async function downloadDocx(title: string, markdown: string) {
  const blob = await markdownToDocxBlob(title, markdown);
  downloadBlob(safeFilename(title, "docx"), blob);
}

