export function safeFilename(name: string, ext: string) {
  const base = (name || "PRD")
    .replace(/[\\/:*?"<>|]+/g, "-")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 80);
  return `${base || "PRD"}.${ext}`;
}

export function downloadBlob(filename: string, blob: Blob) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  // Give Chromium/WebKit a turn to start the download before releasing the Blob URL.
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function downloadMarkdown(title: string, markdown: string) {
  const text = unwrapMarkdown(markdown || "");
  downloadBlob(safeFilename(title, "md"), new Blob([text], { type: "text/markdown;charset=utf-8" }));
}

export function htmlDocumentBlob(html: string) {
  return new Blob([html || ""], { type: "text/html;charset=utf-8" });
}

/** Preview-only iframe sandbox: scripts may run, but not on the workbench origin. */
export const DEMO_PREVIEW_SANDBOX = "allow-scripts";
export const DEMO_PREVIEW_CSP = [
  "default-src 'none'",
  "base-uri 'none'",
  "connect-src 'none'",
  "font-src data:",
  "form-action 'none'",
  "img-src data: blob:",
  "object-src 'none'",
  "script-src 'unsafe-inline'",
  "style-src 'unsafe-inline'",
].join("; ");

/** Add a preview-only CSP without changing the stored Agent HTML. */
export function createSandboxedDemoHtml(html: string) {
  const text = html || "";
  if (!text.trim()) {
    return "";
  }
  const meta = `<meta http-equiv="Content-Security-Policy" content="${DEMO_PREVIEW_CSP}">`;
  // Install CSP before any generated bytes, including malformed pre-head scripts/comments.
  // The stored/exported original remains unchanged.
  return `<!doctype html><html><head>${meta}<meta charset="utf-8"></head><body>${text}</body></html>`;
}

/** The Blob contains only a trusted shell. Generated HTML is encoded inside an opaque-origin iframe. */
export function createDemoPreviewDocument(html: string) {
  const preview = createSandboxedDemoHtml(html);
  if (!preview.trim()) return "";
  const escaped = preview.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  return `<!doctype html><html><head><meta charset="utf-8"><meta name="referrer" content="no-referrer"><title>Demo preview</title><style>html,body,iframe{margin:0;width:100%;height:100%;border:0}body{height:100vh}</style></head><body><iframe title="Isolated demo" sandbox="${DEMO_PREVIEW_SANDBOX}" referrerpolicy="no-referrer" srcdoc="${escaped}"></iframe></body></html>`;
}

export function createDemoPreviewUrl(html: string) {
  const document = createDemoPreviewDocument(html);
  return document ? URL.createObjectURL(htmlDocumentBlob(document)) : "";
}

/** Inline relative css/js for srcdoc preview. Does not run Vite. */
export function inlineStaticPocHtml(indexHtml: string, files: Record<string, string>) {
  let html = indexHtml || "";
  html = html.replace(/<link\b[^>]*rel\s*=\s*['"]stylesheet['"][^>]*>/gi, (tag) => {
    const href = tag.match(/href\s*=\s*['"]([^'"]+)['"]/i)?.[1];
    const path = String(href || "").replace(/^\.\//, "").split(/[?#]/)[0];
    const css = files[path];
    return css ? `<style>\n${css}\n</style>` : tag;
  });
  let injectedMock = false;
  html = html.replace(/<script\b([^>]*)>\s*<\/script>/gi, (tag, attrs: string) => {
    if (/type\s*=\s*['"]module['"]/i.test(attrs)) {
      return tag;
    }
    const src = String(attrs).match(/src\s*=\s*['"]([^'"]+)['"]/i)?.[1];
    const path = String(src || "").replace(/^\.\//, "").split(/[?#]/)[0];
    const js = files[path];
    if (!js) {
      return tag;
    }
    let scriptBlock = "";
    if (!injectedMock && files["data/mock.json"]) {
      scriptBlock += `<script>window.__POC_MOCK__=${files["data/mock.json"]};</script>\n`;
      injectedMock = true;
    }
    scriptBlock += `<script>\n${js}\n</script>`;
    return scriptBlock;
  });
  if (!injectedMock && files["data/mock.json"] && !html.includes("window.__POC_MOCK__")) {
    const mockScript = `<script>window.__POC_MOCK__=${files["data/mock.json"]};</script>`;
    html = html.replace(/<\/body>/i, `${mockScript}</body>`);
  }
  return html;
}

